#!/usr/bin/env node
// Generate packages/plot-core/src/generated/mavgraphs.ts from MAVProxy's
// predefined MAVExplorer graph definitions, vendored (GPLv3) under
// packages/plot-core/vendor/mavproxy-graphs/.
//
// Run manually after re-vendoring:  node scripts/generate-mavgraphs.mjs
//
// The XML is small and regular (<graphs><graph name=..><description/>
// <expression/>..</graph></graphs>), so a hand-rolled reader is enough — no deps.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '..')
const VENDOR_DIR = join(REPO_ROOT, 'packages/plot-core/vendor/mavproxy-graphs')
const OUT_FILE = join(REPO_ROOT, 'packages/plot-core/src/generated/mavgraphs.ts')

// MAVExplorer loads mavgraphs.xml before mavgraphs2.xml and keeps the first
// definition of a name that works, so merged expression lists keep that order.
const SOURCES = ['mavgraphs.xml', 'mavgraphs2.xml']

const ENTITIES = { lt: '<', gt: '>', amp: '&', quot: '"', apos: "'" }

function decodeEntities(text) {
  return text.replace(/&(#x[0-9a-fA-F]+|#[0-9]+|[a-z]+);/g, (whole, entity) => {
    if (entity.startsWith('#x')) return String.fromCodePoint(parseInt(entity.slice(2), 16))
    if (entity.startsWith('#')) return String.fromCodePoint(parseInt(entity.slice(1), 10))
    return ENTITIES[entity] ?? whole
  })
}

function attribute(tagText, name) {
  const match = new RegExp(`\\b${name}\\s*=\\s*("([^"]*)"|'([^']*)')`).exec(tagText)
  return match ? decodeEntities(match[2] ?? match[3]) : undefined
}

function parseGraphs(xml, file) {
  const source = xml.replace(/<!--[\s\S]*?-->/g, '')
  const graphs = []
  const graphRe = /<graph\b([^>]*)>([\s\S]*?)<\/graph>/g
  for (let match = graphRe.exec(source); match; match = graphRe.exec(source)) {
    const name = attribute(match[1], 'name')
    if (!name) throw new Error(`${file}: <graph> without a name`)
    const inner = match[2]
    const descriptionMatch = /<description\s*>([\s\S]*?)<\/description>/.exec(inner)
    const description = decodeEntities(descriptionMatch?.[1] ?? '').replace(/\s+/g, ' ').trim()
    const expressions = []
    const expressionRe = /<expression\s*>([\s\S]*?)<\/expression>/g
    for (let e = expressionRe.exec(inner); e; e = expressionRe.exec(inner)) {
      // Terms are whitespace-separated; normalise line breaks inside one expression.
      const text = decodeEntities(e[1]).replace(/\s+/g, ' ').trim()
      if (text) expressions.push(text)
    }
    graphs.push({ name, description, expressions })
  }
  return graphs
}

const byName = new Map()
for (const file of SOURCES) {
  for (const graph of parseGraphs(readFileSync(join(VENDOR_DIR, file), 'utf8'), file)) {
    const existing = byName.get(graph.name)
    if (!existing) {
      byName.set(graph.name, { ...graph, expressions: [...new Set(graph.expressions)] })
      continue
    }
    // Same name defined twice: one entry, expression lists merged in load order.
    for (const expression of graph.expressions) {
      if (!existing.expressions.includes(expression)) existing.expressions.push(expression)
    }
    if (!existing.description) existing.description = graph.description
  }
}

const q = (text) => JSON.stringify(text)
const entries = [...byName.values()].map((g) =>
  [
    '  {',
    `    name: ${q(g.name)},`,
    `    path: [${g.name.split('/').map(q).join(', ')}],`,
    `    description: ${q(g.description)},`,
    '    expressions: [',
    g.expressions.map((e) => `      ${q(e)}`).join(',\n'),
    '    ]',
    '  }'
  ].join('\n')
)

const header = `// GENERATED by scripts/generate-mavgraphs.mjs — do not edit by hand.
//
// Predefined MAVExplorer graphs from MAVProxy 1.8.74
// (https://github.com/ArduPilot/MAVProxy, MAVProxy/tools/graphs/mavgraphs.xml
// and mavgraphs2.xml), vendored under packages/plot-core/vendor/mavproxy-graphs.
// MAVProxy is GPLv3; this derived data stays GPL-3.0 with the rest of the repo.

import type { GraphDefinition } from '../graph-library.js'

`

writeFileSync(OUT_FILE, `${header}export const MAVGRAPHS: readonly GraphDefinition[] = [\n${entries.join(',\n')}\n]\n`)
console.log(`wrote ${entries.length} graphs to ${OUT_FILE}`)
